import { readFile, readdir, mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { parse } from "yaml";
const root = fileURLToPath(new URL("../../..", import.meta.url));
const read = (p) => readFile(path.join(root, p), "utf8");
export async function agentResources(output) {
  const skills = [];
  const base = "Editor/Sources/AdaEditor/Assets/AgentSkills";
  for (const dir of await readdir(path.join(root, base))) {
    const content = await read(`${base}/${dir}/SKILL.md`);
    const front = parse(content.split("---")[1] || "") || {};
    skills.push({
      id: front.id || front.name || dir,
      name: front.name || dir,
      description: front.description || "",
      content,
    });
  }
  const native = await read(
    "Editor/Sources/AdaEditor/Agent/EditorAgentA2UIModels.swift",
  );
  const match = native.match(
    /static func promptContext\(\)[\s\S]*?return """([\s\S]*?)\n        """/,
  );
  if (!match) throw new Error("Native A2UI contract could not be exported");
  const example = {
    version: "v0.9.1",
    updateComponents: {
      surfaceId: "npc-config",
      components: [
        { id: "root", component: "Column", children: ["name", "submit"] },
        {
          id: "name",
          component: "TextField",
          text: { path: "/npc/name" },
          placeholder: "NPC name",
        },
        {
          id: "submit",
          component: "Button",
          text: "Generate preview",
          action: {
            event: {
              name: "generate_npc_preview",
              context: { name: { path: "/npc/name" } },
            },
          },
        },
      ],
    },
  };
  const contract = match[1]
    .replace(/^        /gm, "")
    .replaceAll(
      "\\(A2UIClient.catalogID)",
      "https://adaengine.org/a2ui/catalogs/forms/v1",
    )
    .replaceAll("\\(componentExample)", JSON.stringify(example));
  if (contract.includes("\\("))
    throw new Error("Unresolved native contract interpolation");
  skills.push({
    id: "ada-chat-ui",
    name: "Interactive chat UI",
    description: "A2UI forms, local scene tools, revisions and submissions.",
    content: contract,
  });
  const docs = JSON.parse(
    await read("Editor/Sources/AdaEditor/Assets/Documentation/catalog.json"),
  );
  const examples = [];
  const walk = async (folder, base = folder) => {
    const files = {};
    for (const e of await readdir(path.join(root, folder), {
      withFileTypes: true,
    })) {
      const p = `${folder}/${e.name}`;
      if (e.isDirectory()) Object.assign(files, await walk(p, base));
      else files[p.slice(base.length + 1)] = await read(p);
    }
    return files;
  };
  for (const id of await readdir(
    path.join(root, "Editor/Sources/AdaEditor/Assets/Examples"),
  )) {
    const files = await walk("Editor/Sources/AdaEditor/Assets/Examples/" + id);
    examples.push({
      id,
      description: files["README.md"]?.slice(0, 600) || id,
      files,
      note: "Native source example. Scene/configuration are generated by native Studio; inspect web capabilities before adapting.",
    });
  }
  await mkdir(output, { recursive: true });
  await writeFile(
    path.join(output, "agent-resources.json"),
    JSON.stringify({
      version: 1,
      skills,
      docs,
      examples,
      apiSource: await read(
        "Sources/AdaScriptCompilerCore/AdaScriptAPICatalog.swift",
      ),
      a2uiCatalog: JSON.parse(
        await read("Sources/AdaA2UI/Resources/catalog.json"),
      ),
    }),
  );
}
